export function getPlan(id: string | null | undefined): Plan | undefined {
  if (!id) return undefined;
  return PLANS.find((plan) => plan.id === id);
}

export function isPlanId(id: string): boolean {
  return PLANS.some((plan) => plan.id === id);
}
